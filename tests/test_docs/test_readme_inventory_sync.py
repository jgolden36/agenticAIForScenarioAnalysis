"""README.md inventory tables must match the registry's implementation info.

The block between ``<!-- inventory:start -->`` and ``<!-- inventory:end -->``
is generated by ``python slurm/scripts/build_model_inventory.py --update-readme``.
This test fails when an adapter's status label changes without regenerating
the README, which is how the paper's inventory drifted from the code before
the revision.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from slurm.scripts.build_model_inventory import (  # noqa: E402
    README_END,
    README_START,
    readme_tables,
    static_inventory,
)

ROOT = Path(__file__).resolve().parents[2]


def _readme_block() -> str:
    text = (ROOT / "README.md").read_text(encoding="utf-8")
    m = re.search(re.escape(README_START) + r"(.*?)" + re.escape(README_END), text, re.DOTALL)
    assert m, "README.md is missing the inventory markers"
    return m.group(1).strip()


def _rows_from_block(block: str) -> dict[str, str]:
    """adapter path -> status cell for every table row in the block."""
    out: dict[str, str] = {}
    for line in block.splitlines():
        if not line.startswith("| ") or line.startswith("| Model") or line.startswith("|---"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3:
            continue
        path = cells[1].strip("`")
        if path.startswith("src/models/"):
            out[path] = cells[2]
    return out


def test_readme_block_matches_generated_tables():
    rows = static_inventory()
    expected = readme_tables(rows).strip()
    assert _readme_block() == expected, (
        "README inventory block is stale; run "
        "`python slurm/scripts/build_model_inventory.py --update-readme`"
    )


def test_readme_status_cells_match_registry():
    rows = static_inventory()
    by_path = {r["adapter_path"]: r for r in rows}
    readme_rows = _rows_from_block(_readme_block())
    assert readme_rows, "no inventory rows parsed from README"
    for path, status in readme_rows.items():
        assert path in by_path, f"README lists unknown adapter {path}"
        assert status == by_path[path]["status_label"], (path, status, by_path[path]["status_label"])
    missing = set(by_path) - set(readme_rows)
    assert not missing, f"adapters missing from README inventory: {sorted(missing)}"
