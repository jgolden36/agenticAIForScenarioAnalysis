"""Static implementation facts for every registered domain-model adapter.

One :class:`~src.models.base.ImplementationInfo` per ``model_id``. The
registry's :meth:`ModelRegistry.inventory` and
``slurm/scripts/build_model_inventory.py`` read this table to produce the
run-independent model inventory (platform, implementation available,
calibration sources, key equations, limitations, licence notes), and the
coverage ledger uses ``mode_when_executed`` as the last-resort label for
completed cells whose run records carry no mode marker.

Keep this table in sync with the adapters: the test suite checks that every
registered adapter has an entry and that ``README.md``'s inventory tables
match the ``status_label`` values here.

Vocabulary for ``status_label``:

* ``Real`` — the adapter runs the upstream model code / binary end to end
  (an external runtime such as GAMS, Octave, Julia or a Python package may
  be required at execution time).
* ``Real (config-aware)`` — same, but the path only activates with a YAML
  config under ``configs/model_configs/``; without one ``execute()`` raises
  ``NotImplementedError``.
* ``Real (analytical MVP)`` — a closed-form, literature-calibrated reduction
  implemented inside the adapter runs by default.
* ``Real (analytical MVP) + config-aware full path`` — the reduction runs by
  default and the full upstream path activates with a config.
* ``Real (published-output ingestion) + optional full path`` — the adapter
  ingests officially published model outputs by default (EIA AEO tables)
  and can drive the real model when configured.
* ``Config-aware stub`` — config validation and dispatch glue exist, but no
  execute path runs yet.
* ``Stub`` — typed schemas only; ``execute()`` raises ``NotImplementedError``.
"""

